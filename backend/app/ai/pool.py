"""Database-persisted and in-memory verified question pool for TRELLIS AI Gateway.

Survives server restarts, synchronizes across workers, and eliminates learner latency.
Truthfully tags provenance:
- "model" when pre-generated by Ollama / Cloud models
- "curated" when populated from vetted curriculum packs
"""

from __future__ import annotations

import collections
import hashlib
import logging
import threading
from typing import Any

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.ai.prompts import PROMPT_VERSION
from app.ai.providers.procedural import ProceduralAIProvider
from app.ai.quality_gates import verify_coding_quality, verify_mcq_quality
from app.ai.schemas import Provenance
from app.models.practice import AIQuestionPool

logger = logging.getLogger(__name__)


def compute_question_hash(text: str) -> str:
    clean = " ".join((text or "").strip().lower().split())
    return hashlib.sha256(clean.encode("utf-8")).hexdigest()[:16]


class VerifiedPoolManager:
    """Manages pre-verified problem queues backed by Postgres/SQLite database and in-memory buffers."""

    def __init__(self, target_per_bucket: int = 4) -> None:
        self.target_per_bucket = target_per_bucket
        self._memory_pools: dict[str, collections.deque[dict[str, Any]]] = collections.defaultdict(collections.deque)
        self._lock = threading.Lock()
        self._procedural = ProceduralAIProvider()
        # Seed initial memory buffers for immediate availability (MCQs fast-seeded; coding seeded on demand)
        for fld in ["Python", "SQL"]:
            self.populate_memory_fallback(fld, "MCQ", "MEDIUM", count=self.target_per_bucket)

    def _bucket_key(self, field: str, mode: str, difficulty: str = "MEDIUM") -> str:
        return f"{field.strip().lower()}:{mode.strip().lower()}:{difficulty.strip().lower()}"

    def get_question_from_db(
        self,
        db: Session,
        field: str,
        mode: str,
        difficulty: str = "MEDIUM",
        seen_hashes: set[str] | None = None,
        learner_id: str | None = None,
    ) -> dict[str, Any] | None:
        """Fetch unused verified question from database pool, respecting learner deduplication."""
        fld = field.strip()
        diff = difficulty.strip().upper()
        norm_mode = mode.strip().upper()
        hashes = seen_hashes or set()

        query = (
            select(AIQuestionPool)
            .where(
                AIQuestionPool.field.ilike(fld),
                AIQuestionPool.mode == norm_mode,
                AIQuestionPool.difficulty == diff,
                AIQuestionPool.verified == True,
            )
            .order_by(func.random())
            .limit(25)
        )
        candidates = db.execute(query).scalars().all()

        for cand in candidates:
            if cand.question_hash not in hashes:
                data = dict(cand.question_data_json)
                prov = dict(cand.provenance_json) if cand.provenance_json else {}
                prov["served_from"] = "pool"
                data["provenance"] = prov
                data["source"] = "model" if prov.get("provider") in ("ollama", "cloud") else "curated"
                return data

        return None

    def store_verified_question(
        self,
        db: Session,
        problem: dict[str, Any],
        provenance: dict[str, Any],
        field: str,
        mode: str,
        difficulty: str = "MEDIUM",
        category: str = "Technical Knowledge",
        language: str | None = None,
    ) -> AIQuestionPool:
        """Persist a newly verified question into the database pool."""
        q_text = problem.get("question") or problem.get("question_text") or problem.get("statement") or ""
        q_hash = compute_question_hash(q_text)

        pool_entry = AIQuestionPool(
            field=field,
            category=category,
            difficulty=difficulty.upper(),
            mode=mode.upper(),
            language=language,
            title=problem.get("title", f"{field} Problem"),
            question_hash=q_hash,
            question_data_json=problem,
            provenance_json=provenance,
            is_used=False,
            verified=True,
        )
        db.add(pool_entry)
        db.commit()
        db.refresh(pool_entry)
        return pool_entry

    def get_pool_counts_from_db(self, db: Session) -> dict[str, int]:
        """Query real database counts for all unused verified questions grouped by bucket."""
        rows = (
            db.execute(
                select(
                    AIQuestionPool.field,
                    AIQuestionPool.mode,
                    AIQuestionPool.difficulty,
                    func.count(AIQuestionPool.id),
                )
                .where(AIQuestionPool.is_used == False, AIQuestionPool.verified == True)
                .group_by(AIQuestionPool.field, AIQuestionPool.mode, AIQuestionPool.difficulty)
            )
            .all()
        )
        counts: dict[str, int] = {}
        for f, m, d, c in rows:
            key = f"{f.lower()}:{m.lower()}:{d.lower()}"
            counts[key] = int(c)
        return counts

    def get_pool_counts(self) -> dict[str, int]:
        """Return counts of available questions across all memory bucket pools."""
        with self._lock:
            return {k: len(v) for k, v in self._memory_pools.items() if len(v) > 0}

    def get_question(self, field: str, mode: str, difficulty: str = "MEDIUM") -> dict[str, Any] | None:
        """Convenience method returning question from memory pool, replenishing if depleted."""
        item = self.get_memory_question(field, mode, difficulty)
        if not item:
            self.populate_memory_fallback(field, mode, difficulty, count=self.target_per_bucket)
            item = self.get_memory_question(field, mode, difficulty)
        return item

    def get_memory_question(self, field: str, mode: str, difficulty: str = "MEDIUM") -> dict[str, Any] | None:
        """Fallback to in-memory queue if database session is omitted."""
        key = self._bucket_key(field, mode, difficulty)
        with self._lock:
            q = self._memory_pools.get(key)
            if q and len(q) > 0:
                item = q.popleft()
                item.setdefault("provenance", {})["served_from"] = "pool"
                return item
        return None

    def populate_memory_fallback(self, field: str, mode: str, difficulty: str = "MEDIUM", count: int = 2) -> None:
        key = self._bucket_key(field, mode, difficulty)
        for _ in range(count):
            try:
                if mode.upper() == "MCQ":
                    prob = self._procedural.generate_mcq(field=field, difficulty=difficulty)
                    if verify_mcq_quality(prob):
                        prob.provenance.served_from = "pool"
                        prob.source = "procedural"
                        with self._lock:
                            self._memory_pools[key].append(prob.model_dump())
                else:
                    lang = "sql" if "sql" in field.lower() else ("java" if "java" in field.lower() else "python")
                    prob = self._procedural.generate_coding(field=field, difficulty=difficulty, language=lang)
                    if verify_coding_quality(prob):
                        prob.provenance.served_from = "pool"
                        prob.source = "procedural"
                        with self._lock:
                            self._memory_pools[key].append(prob.model_dump())
            except Exception as e:
                logger.warning("Error pre-filling memory bucket '%s': %s", key, e)
