export class AssistantComponent {
  private readonly authService = inject(AuthService);

  readonly isOpen = signal<boolean>(false);
  readonly loading = signal<boolean>(false);
  readonly isReceivingStream = signal<boolean>(false);
  readonly lastFailedMessage = signal<string | null>(null);

  userInput = '';
  private activeAbortController: AbortController | null = null;

  readonly roleName = computed(() => {
    return this.authService.primaryRole() || 'LEARNER';
  });

  readonly suggestedPrompts = computed(() => {
    const role = this.roleName();
    if (role === 'ADMIN') {
      return ['Department dashboard summary', 'Review Talent Spotlight alerts', 'Assessments conducted per mentor'];
    }
    if (role === 'MENTOR') {
      return ['Which learners need attention?', 'Upcoming meetings today', 'Pending assessment submissions'];
    }
    return ['My upcoming meetings', 'What are my weak topics?', 'My coding streak status'];
  });

  readonly messages = signal<ChatMessage[]>([
    {
      id: 'welcome',
      sender: 'assistant',
      text: 'Hello! I am your TRELLIS assistant. I provide role-governed intelligence for your learning, assessments, and metrics at CSM Technologies.',
      time: 'Now',
    },
  ]);

  toggleOpen(): void {
    this.isOpen.update((v) => !v);
  }

  sendQuickPrompt(prompt: string): void {
    this.userInput = prompt;
    this.sendMessage();
  }

  stopGenerating(): void {
    if (this.activeAbortController) {
      this.activeAbortController.abort();
      this.activeAbortController = null;
    }
    this.loading.set(false);
    this.isReceivingStream.set(false);
    // Mark current streaming message as finished
    this.messages.update((list) =>
      list.map((m) => (m.isStreaming ? { ...m, isStreaming: false } : m))
    );
  }

  retryLastMessage(): void {
    const lastMsg = this.lastFailedMessage();
    if (lastMsg) {
      this.userInput = lastMsg;
      this.sendMessage();
    }
  }

  async sendMessage(): Promise<void> {
    const query = this.userInput.trim();
    if (!query) return;

    const userMsgId = 'u-' + Date.now();
    const assistantMsgId = 'a-' + Date.now();

    this.messages.update((list) => [
      ...list,
      {
        id: userMsgId,
        sender: 'user',
        text: query,
        time: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
      },
      {
        id: assistantMsgId,
        sender: 'assistant',
        text: '',
        time: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
        isStreaming: true,
      },
    ]);

    this.userInput = '';
    this.loading.set(true);
    this.isReceivingStream.set(false);
    this.lastFailedMessage.set(null);

    const role = this.roleName().toLowerCase();
    const endpoint = `/api/v1/${role}/chatbot/stream`;
    const token = this.authService.accessToken();

    this.activeAbortController = new AbortController();

    try {
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          ...(token ? { Authorization: `Bearer ${token}` } : {}),
        },
        body: JSON.stringify({ message: query }),
        signal: this.activeAbortController.signal,
      });

      if (!response.ok) {
        throw new Error(`Server returned HTTP ${response.status}`);
      }

      if (!response.body) {
        throw new Error('Streaming body not available.');
      }

      const reader = response.body.getReader();
      const decoder = new TextDecoder('utf-8');
      let buffer = '';

      while (true) {
        const { done, value } = await reader.read();
        if (done) break;

        this.isReceivingStream.set(true);
        buffer += decoder.decode(value, { stream: true });
        const lines = buffer.split('\n');
        buffer = lines.pop() || '';

        let currentEvent = 'message';
        for (const line of lines) {
          const trimmed = line.trim();
          if (trimmed.startsWith('event:')) {
            currentEvent = trimmed.substring(6).trim();
          } else if (trimmed.startsWith('data:')) {
            const rawData = trimmed.substring(5).trim();
            try {
              const data = JSON.parse(rawData);
              if (currentEvent === 'delta' && data.delta) {
                this.messages.update((list) =>
                  list.map((m) =>
                    m.id === assistantMsgId ? { ...m, text: m.text + data.delta } : m
                  )
                );
              } else if (currentEvent === 'done') {
                const isOffline = data.provenance?.served_from === 'fallback';
                this.messages.update((list) =>
                  list.map((m) =>
                    m.id === assistantMsgId
                      ? {
                          ...m,
                          isStreaming: false,
                          isOfflineCard: isOffline,
                          provenance: data.provenance,
                        }
                      : m
                  )
                );
              } else if (currentEvent === 'error') {
                this.messages.update((list) =>
                  list.map((m) =>
                    m.id === assistantMsgId
                      ? {
                          ...m,
                          text: data.error || 'The AI assistant is temporarily unavailable.',
                          isStreaming: false,
                          isOfflineCard: true,
                        }
                      : m
                  )
                );
              }
            } catch {
              // Non-JSON SSE line
            }
          }
        }
      }
    } catch (err: any) {
      if (err.name === 'AbortError') {
        // Aborted by user
        return;
      }
      this.lastFailedMessage.set(query);
      this.messages.update((list) =>
        list.map((m) =>
          m.id === assistantMsgId
            ? {
                ...m,
                text: 'Connection to TRELLIS Assistant timed out or failed. Please check network and retry.',
                isStreaming: false,
                isOfflineCard: true,
              }
            : m
        )
      );
    } finally {
      this.loading.set(false);
      this.isReceivingStream.set(false);
      this.activeAbortController = null;
      this.messages.update((list) =>
        list.map((m) => (m.isStreaming ? { ...m, isStreaming: false } : m))
      );
    }
  }
}
